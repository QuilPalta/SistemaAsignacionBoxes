package CapaDTO;

public class Box {
    private int idBox;
    private String nombreBox;
    private int piso;
    private String tipo;
    private String estado;

    public int getIdBox() { return idBox; }
    public void setIdBox(int idBox) { this.idBox = idBox; }

    public String getNombreBox() { return nombreBox; }
    public void setNombreBox(String nombreBox) { this.nombreBox = nombreBox; }

    public int getPiso() { return piso; }
    public void setPiso(int piso) { this.piso = piso; }

    public String getTipo() { return tipo; }
    public void setTipo(String tipo) { this.tipo = tipo; }

    public String getEstado() { return estado; }
    public void setEstado(String estado) { this.estado = estado; }
}

